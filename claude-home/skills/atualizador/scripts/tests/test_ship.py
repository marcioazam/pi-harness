    def test_ship_from_the_default_branch_creates_the_branch_and_delivers_end_to_end(
        self,
    ):
        (self.work / "new.txt").write_text("n\n")
        head = "{REV:feat/x}"  # the stub resolves the committed head when gh asks
        self.gh_rules(
            {"match": ["pr", "list"], "stdout": "[]"},
            {"match": ["pr", "create"], "stdout": CREATE_URL},
            {"match": ["pr", "checks"], "stdout": GREEN},
            {"match": ["pr", "merge"], "stdout": ""},
            {
                "match": ["pr", "view"],
                "seq": [
                    {"stdout": pr_json(s, headRefOid=head, headRefName="feat/x")}
                    for s in ("OPEN", "OPEN", "MERGED", "MERGED")
                ],
            },
        )
        code, out = self.ship(
            self.work, *self.path_args("--branch", "feat/x", "--main-checkout", self.work)
        )  # fmt: skip
        self.assertEqual(
            (code, out["ok"], out["branch_created"]), (0, True, "feat/x"), out
        )
        self.assertEqual(
            list(out["steps"]),
            [
                "commit",
                "integrate",
                "gate",
                "publish",
                "ci",
                "merge",
                "sync",
                "cleanup",
            ],
        )
        self.assertEqual(git(self.work, "branch", "--show-current"), "main")
        self.assertEqual(git(self.work, "branch", "--list", "feat/x"), "")
        self.assertEqual(git(self.origin, "branch", "--list", "feat/x"), "")

