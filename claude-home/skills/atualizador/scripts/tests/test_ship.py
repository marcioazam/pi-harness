    def test_stops_at_the_first_failure_then_resumes(self):
        wt = self.worktree()
        sha = git(wt, "rev-parse", "HEAD")
        self.rules(sha, ["OPEN"])
        code, out = self.ship(wt, check="t=exit 1")
        self.assertEqual(
            (code, out["reason"], out["stopped_at"]), (4, "checks_failed", "gate")
        )
        self.assertEqual(list(out["steps"]), ["integrate"])
        self.assertEqual(self.gh_calls_of("pr", "create"), [])

        code, out = self.ship(wt, "--no-merge")
        self.assertEqual((code, out["pr"]), (0, 7), out)
        self.assertEqual(list(out["steps"]), ["integrate", "gate", "publish"])
        self.assertEqual(len(self.gh_calls_of("pr", "create")), 1)

        open_pr = f"[{pr_json(headRefOid=sha)}]"
        self.rules(sha, ["OPEN"], listing=open_pr, checks={"rc": 1, "stdout": RED})
        self.gh_rules(*self.read_rules(), {"match": ["api"], "stdout": "[]"})
        code, out = self.ship(wt)
        self.assertEqual(
            (code, out["reason"], out["stopped_at"]), (5, "ci_unknown", "ci")
        )
        self.assertEqual(out["steps"]["gate"], {"skipped": "proof_valid"})
        self.assertFalse(out["steps"]["publish"]["created"])
        self.assertEqual(len(self.gh_calls_of("pr", "create")), 1)

        self.rules(sha, ["OPEN", "OPEN", "MERGED"], listing=open_pr)
        code, out = self.ship(wt)
        self.assertEqual((code, out["steps"]["merge"]["merged"]), (0, True), out)

