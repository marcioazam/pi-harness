from support import Base, conflict_setup, git, pr_json

CREATE_URL = "https://github.test/o/r/pull/7\n"
GREEN = "build\tpass\t1m\thttps://ci.test/build\t\n"
RED = "build\tfail\t1m\thttps://ci.test/build\t\n"


class Ship(Base):
    def rules(self, sha, views, listing="[]", checks=None):
        self.gh_rules(
            {"match": ["pr", "list"], "stdout": listing},
            {"match": ["pr", "create"], "stdout": CREATE_URL},
            {"match": ["pr", "checks"], **(checks or {"stdout": GREEN})},
            {"match": ["pr", "merge"], "stdout": ""},
            {
                "match": ["pr", "view"],
                "seq": [{"stdout": pr_json(s, headRefOid=sha)} for s in views],
            },
        )

    def ship(self, repo, *extra, check="t=true"):
        return self.call(
            "ship", "--repo", repo, "--base", "main", "--check", check, *extra
        )

    def test_full_chain_from_a_linked_worktree(self):
        wt = self.worktree()
        sha = git(wt, "rev-parse", "HEAD")
        self.rules(sha, ["OPEN", "OPEN", "MERGED", "MERGED"])
        code, out = self.ship(
            wt, "--main-checkout", self.work, "--attribution", "Generated by tests"
        )
        self.assertEqual(
            (code, out["ok"], out["stopped_at"], out["pr"]), (0, True, None, 7), out
        )
        self.assertEqual(out["merge_commit"], "m" * 40)
        self.assertEqual(
            list(out["steps"]),
            ["integrate", "gate", "publish", "ci", "merge", "sync", "cleanup"],
        )
        (merge,) = self.gh_calls_of("pr", "merge")
        self.assertEqual(merge[merge.index("--match-head-commit") + 1], sha)
        for flag in ("--admin", "--delete-branch", "--force"):
            self.assertNotIn(flag, merge)
        self.assertFalse(wt.exists())
        self.assertEqual(git(self.work, "branch", "--show-current"), "main")
        self.assertEqual(
            (
                git(self.work, "branch", "--list", "feat"),
                git(self.origin, "branch", "--list", "feat"),
            ),
            ("", ""),
        )

